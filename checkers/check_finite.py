"""Model, DP, rival, and full CNF reconstruction checks. SPDX-License-Identifier: Apache-2.0"""
from core import *
import random, time

def run():
    start = time.monotonic()
    m = manifest()
    SCRATCH.mkdir(parents=True, exist_ok=True)
    # Exhaustive sequence checks against complete small structural enumeration.
    checked = 0
    rng = random.Random(17042026)
    for n in range(13):
        structures = legal_matchings(n)
        seqs = (map(''.join, product(ABC, repeat=n)) if n <= 7 else
                (''.join(rng.choices(ABC, k=n)) for _ in range(128)))
        for seq in seqs:
            feasible = [(p, score) for p, score in structures if all(seq[i]+seq[j] in PAIRS for i,j in p)]
            best = max(score for p, score in feasible)
            count = sum(score == best for p, score in feasible)
            actual = fold(seq)
            assert actual[:2] == (best, count), (seq, actual, best, count)
            assert parse(actual[2]) in {p for p, score in feasible if score == best}
            checked += 1
    seq = (INPUT / 'D12-sequence.txt').read_text().strip()
    assert seq == m['D12_lower']['sequence']
    result = fold(seq)
    assert result == (12, 1, target(12))
    assert result[2] == m['D12_lower']['target']
    assert all(seq[i]+seq[j] in PAIRS for i,j in parse(result[2]))
    assert check_pairs(parse(result[2]),len(seq)) == 12
    # The normalization inclusions and color symmetry, checked on the full alphabet.
    neighbors = {a: {b for b in ABC if a+b in PAIRS} for a in ABC}
    assert neighbors['A'] <= neighbors['G'] and neighbors['C'] <= neighbors['U']
    assert {ab.translate(TAU) for ab in PAIRS} == PAIRS
    assert {a+WC[a] for a in ABC} == {(a+WC[a]).translate(TAU) for a in ABC}
    assert {'A'.translate(TAU), 'C'.translate(TAU)} == {'A','C'}
    save('dp-model.json', {'small_sequences':checked, 'exhaustive_through_n':7,
        'random_per_length_8_to_12':128, 'D12':{'score':result[0], 'count':result[1], 'witness':result[2]},
        'normalization_alphabet_checks':True, 'elapsed_seconds':time.monotonic()-start})
    print('DP/model checked',checked,'D12',result[:2],flush=True)
    output = {}
    for label,t,threshold,sep,fix in [('D13',target(13),13,2,True),('U14',u_target(),14,1,False)]:
        begin = time.monotonic()
        item = m['D13'] if label == 'D13' else m['D_ge_14']
        if label == 'U14': assert t == item['target_U14']
        name = item['rivals']
        with gzip.open(INPUT/name,'rb') as f: raw = f.read()
        assert hashlib.sha256(raw).hexdigest() == item['rivals_plain_sha256']
        rivals = raw.decode('ascii').splitlines()
        assert len(rivals) == (227280 if label=='D13' else 1731)
        assert len(set(rivals)) == len(rivals)
        scores = Counter()
        for r in rivals:
            p, score = check_rival(r,t,threshold); scores[score] += 1
        if label == 'D13': assert rivals == sorted(rivals)
        try:
            bad = list(rivals[0]); bad[next(i for i,c in enumerate(bad) if c=='(')] = '.'
            check_rival(''.join(bad), t, threshold)
            raise AssertionError('corrupted rival accepted')
        except ValueError as e:
            fault = str(e)
        variables, clauses, base = formula(t,rivals,sep,fix)
        path = SCRATCH / (label+'-rebuilt.cnf')
        write_cnf(path,variables,clauses)
        expected_sha = item['cnf_sha256'] if label=='D13' else item['base_cnf_sha256']
        assert sha(path) == expected_sha, label + ' regenerated bytes differ'
        own = clause_multiset(clauses)
        record = {'rivals':len(rivals),'scores':dict(scores),'variables':variables,'base_clauses':base,
                  'clauses':len(clauses),'canonical_byte_hash_matches':True,'byte_equal':sha(path)==expected_sha,
                  'rebuilt_sha256':sha(path),'input_sha256':expected_sha,'corrupt_rival_rejected':fault}
        if label == 'D13':
            assert (variables,base,len(clauses)) == (3158,41128,268408)
        else:
            assert (variables,base,len(clauses)) == (5044,67129,68860)
            cases = []
            for case in item['cases']:
                words = case['sorted_words']
                assert len(words)==13 and words==sorted(words) and len(set(words))==13
                units = [(x(4+7*k+q,a),) for k,w in enumerate(words) for q,a in enumerate(w)]
                assert len(units)==65
                case_path = SCRATCH / f"U14-case-{case['index']:02}.cnf"
                write_cnf(case_path, variables, clauses + units)
                assert sha(case_path) == case['cnf_sha256']
                cv, cc = read_cnf_for_comparison(case_path)
                assert cv == variables and clause_multiset(cc) == own + clause_multiset(units)
                cases.append({'index':case['index'],'multiset_equal':True,'clauses':len(cc), 'sha256':case['cnf_sha256']})
            record['cases'] = cases
        record['elapsed_seconds'] = time.monotonic()-begin
        output[label] = record
        save('finite-checks.json',output)
        print(label,json.dumps(record if label=='D13' else {k:v for k,v in record.items() if k!='cases'}),flush=True)
    print('All finite structural and CNF checks passed',flush=True)

if __name__ == '__main__': run()
